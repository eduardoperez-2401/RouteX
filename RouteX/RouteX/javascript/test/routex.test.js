import test from "node:test";
import assert from "node:assert/strict";
import { RouteX } from "../src/routex.js";
import fs from "node:fs";
const d = new URL("../../datos/", import.meta.url);
const read = n => JSON.parse(fs.readFileSync(new URL(n,d),"utf8"));
const make = () => new RouteX(read("ubicaciones.json"),read("conexiones.json"),read("vehiculos.json"));
test("calcula ruta por distancia", () => assert.ok(make().shortest("A","F","distance")));
test("calcula ruta por tiempo", () => assert.equal(make().shortest("A","F","time").optimized_for,"time"));
test("calcula ruta por costo", () => assert.ok(make().shortest("A","F","cost").cost > 0));
test("rechaza ubicación inexistente", () => assert.throws(() => make().shortest("A","Z")));
test("asigna vehículo y lo ocupa", () => { const a=make(); const v=a.assignVehicle(6); assert.ok(v); assert.equal(v.available,false); });
test("sin capacidad deja pendiente", () => assert.equal(make().assignVehicle(99),null));
